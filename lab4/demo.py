from filesystem import FileSystem


def demo() -> None:
    fs = FileSystem(block_size=128)
    fs.mkfs(8)
    print("mkfs 8")
    print("create some.dat -> inode", fs.create("some.dat"))
    print("truncate some.dat 1024")
    fs.truncate("some.dat", 1024)
    print("stat some.dat ->", fs.stat("some.dat"))
    fd = fs.open("some.dat")
    print("open some.dat -> fd", fd)
    fs.write(fd, b"0123456789")
    fs.seek(fd, 7)
    print("read 0 2 ->", fs.read(fd, 2))
    fs.seek(fd, 256)
    fs.write(fd, b"abcdefg")
    print("stat some.dat ->", fs.stat("some.dat"))
    fs.link("some.dat", "other.dat")
    print("link some.dat other.dat; ls ->", fs.ls())
    fs.unlink("some.dat")
    print("unlink some.dat; ls ->", fs.ls())
    fs.seek(fd, 0)
    print("read 0 10 ->", fs.read(fd, 10))
    fs.unlink("other.dat")
    print("unlink other.dat; fd still valid ->", fs.read(fd, 1))
    fs.close(fd)
    print("close 0; file released ->", fs.inodes[1] is None)
